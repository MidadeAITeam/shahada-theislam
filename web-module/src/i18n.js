const TABLES = { en, ar };
const RTL = new Set(['ar', 'fa', 'ur', 'he', 'ps']);

// The platform names a few locales differently from the API (ISO 639-1).
const API_LANG = { po: 'pt', fil: 'tl' };

export function apiLang(locale) {
  const l = (locale || 'en').toLowerCase().split('-')[0];
  return API_LANG[l] || l;
}

export function isRtl(locale) {
  return RTL.has(apiLang(locale));
}

export function t(locale, key, vars) {
  const table = TABLES[apiLang(locale)] || en;
  let s = table[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

/** A translator bound to a (reactive) locale getter, for use inside components. */
export function useT(getLocale) {
  return (key, vars) => t(typeof getLocale === 'function' ? getLocale() : getLocale, key, vars);
}
