/** Look up a (dotted) key in the current language and fill {placeholders}. */
export function t(key, vars) {
  let v = key.split(".").reduce((o, k) => (o == null ? o : o[k]), M[lang.value]);
  if (v == null) v = key.split(".").reduce((o, k) => (o == null ? o : o[k]), M.en) ?? key;
  if (typeof v === "string" && vars) v = v.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
  return v;
}

export function errorText(code) {
  const v = t(`err.${code}`);
  return typeof v === "string" && !v.startsWith("err.") ? v : t("err.generic");
}

export function toggleLang() {
  lang.value = lang.value === "ar" ? "en" : "ar";
}
